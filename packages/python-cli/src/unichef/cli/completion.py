"""Shell completion scripts generated from the argparse tree (PRD §5.7). Operation ids are
completed at run time with ``unichef ops --ids``."""

import argparse
from dataclasses import dataclass, field

from unichef.cli.parser import UniChefParser, build_parser

FILE_METAVARS = frozenset({"FILE", "PATH"})


@dataclass(slots=True)
class Spec:
    """What one parser accepts."""

    name: str
    summary: str = ""
    flags: list[str] = field(default_factory=list)
    values: dict[str, list[str]] = field(default_factory=dict)
    """Flags that take a value: their choices, or ``[]`` for free text or a path."""
    files: set[str] = field(default_factory=set)
    subs: list["Spec"] = field(default_factory=list)


def _spec(name: str, summary: str, parser: argparse.ArgumentParser) -> Spec:
    spec = Spec(name, summary)
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {c.dest: c.help or "" for c in action._choices_actions}
            spec.subs = [_spec(n, helps.get(n, ""), p) for n, p in action.choices.items()]
            continue
        if not action.option_strings:
            continue
        spec.flags += action.option_strings
        if action.nargs != 0:
            for flag in action.option_strings:
                spec.values[flag] = [str(c) for c in action.choices or ()]
                if action.metavar in FILE_METAVARS:
                    spec.files.add(flag)
    return spec


def model() -> Spec:
    root, _ = build_parser()
    return _spec("unichef", "", root)


def _q(text: str) -> str:
    return "'" + text.replace("'", "'\\''") + "'"


# -- bash / zsh --------------------------------------------------------------------------


def _bash_values(root: Spec) -> list[str]:
    lines: list[str] = []
    every: dict[str, Spec] = {}
    stack = [root]
    while stack:
        spec = stack.pop()
        for flag in spec.values:
            every.setdefault(flag, spec)
        stack += spec.subs
    for flag in sorted(every):
        spec = every[flag]
        choices = spec.values[flag]
        if choices:
            lines.append(
                f'    {flag}) COMPREPLY=($(compgen -W {_q(" ".join(choices))} -- "$cur")); return;;'
            )
        elif flag in spec.files:
            lines.append(f'    {flag}) COMPREPLY=($(compgen -f -- "$cur")); return;;')
        else:
            lines.append(f"    {flag}) return;;")
    return lines


def bash(root: Spec) -> str:
    takes_value = sorted({f for s in [root, *root.subs] for f in s.values}
                         | {f for s in root.subs for sub in s.subs for f in sub.values})  # fmt: skip
    cases: list[str] = []
    for spec in root.subs:
        flags = " ".join(spec.flags)
        if spec.subs:
            inner = [f"        {sub.name}) words={_q(' '.join(sub.flags))};;" for sub in spec.subs]
            cases += [
                f"    {spec.name})",
                f'      if [[ -z "$sub" ]]; then words={_q(" ".join(s.name for s in spec.subs))}',
                '      else case "$sub" in',
                *inner,
                "      esac; fi;;",
            ]
        elif spec.name == "op":
            cases += [
                "    op)",
                '      if [[ -z "$sub" && "$cur" != -* ]]; then words="$(unichef ops --ids 2>/dev/null)"',
                f"      else words={_q(flags)}; fi;;",
            ]
        else:
            cases.append(f"    {spec.name}) words={_q(flags)};;")
    commands = " ".join(s.name for s in root.subs)
    return "\n".join([
        "# unichef bash completion. Generated by `unichef completion bash`.",
        "_unichef() {",
        '  local cur="${COMP_WORDS[COMP_CWORD]}" prev="${COMP_WORDS[COMP_CWORD-1]}"',
        '  local cmd="" sub="" words="" i skip=0',
        "  for ((i = 1; i < COMP_CWORD; i++)); do",
        '    local w="${COMP_WORDS[i]}"',
        "    if ((skip)); then skip=0; continue; fi",
        '    case "$w" in',
        f"      {'|'.join(takes_value)}) skip=1;;",
        "      -*) ;;",
        '      *) if [[ -z "$cmd" ]]; then cmd="$w"; elif [[ -z "$sub" ]]; then sub="$w"; fi;;',
        "    esac",
        "  done",
        '  case "$prev" in',
        *_bash_values(root),
        "  esac",
        '  case "$cmd" in',
        f'    "") words={_q(commands + " " + " ".join(root.flags))};;',
        *cases,
        "  esac",
        '  COMPREPLY=($(compgen -W "$words" -- "$cur"))',
        "}",
        "complete -o default -F _unichef unichef",
        "",
    ])  # fmt: skip


def zsh(root: Spec) -> str:
    body = bash(root).split("\n", 1)[1]
    return "\n".join([
        "#compdef unichef",
        "# unichef zsh completion. Generated by `unichef completion zsh`.",
        "autoload -U +X bashcompinit && bashcompinit",
        body,
    ])  # fmt: skip


# -- fish ----------------------------------------------------------------------------------


def _fish_flag(flag: str) -> str:
    return f"-l {flag[2:]}" if flag.startswith("--") else f"-s {flag[1:]}"


def _fish_flags(spec: Spec, condition: str) -> list[str]:
    lines = []
    for flag in spec.flags:
        cond = f" -n {_q(condition)}" if condition else ""
        extra = ""
        if flag in spec.values:
            choices = spec.values[flag]
            extra = (
                f" -xa {_q(' '.join(choices))}"
                if choices
                else " -r" + (" -F" if flag in spec.files else "")
            )
        lines.append(f"complete -c unichef{cond} {_fish_flag(flag)}{extra}")
    return lines


def fish(root: Spec) -> str:
    lines = ["# unichef fish completion. Generated by `unichef completion fish`.",
             "complete -c unichef -f"]  # fmt: skip
    lines += _fish_flags(root, "")
    for spec in root.subs:
        lines.append(
            f"complete -c unichef -n __fish_use_subcommand -a {spec.name} -d {_q(spec.summary)}"
        )
    for spec in root.subs:
        seen = f"__fish_seen_subcommand_from {spec.name}"
        local = Spec(spec.name, flags=[f for f in spec.flags if f not in root.flags],
                     values=spec.values, files=spec.files)  # fmt: skip
        lines += _fish_flags(local, seen)
        if spec.name == "op":
            lines.append(f"complete -c unichef -n {_q(seen)} -a '(unichef ops --ids 2>/dev/null)'")
        for sub in spec.subs:
            lines.append(f"complete -c unichef -n {_q(seen)} -a {sub.name} -d {_q(sub.summary)}")
    return "\n".join(lines) + "\n"


# -- PowerShell ----------------------------------------------------------------------------


def _ps_list(items: list[str]) -> str:
    return "@(" + ", ".join("'" + i.replace("'", "''") + "'" for i in items) + ")"


def powershell(root: Spec) -> str:
    entries = []
    for spec in root.subs:
        subs = {s.name: s.flags for s in spec.subs}
        sub_entries = "; ".join(f"'{n}' = {_ps_list(f)}" for n, f in subs.items())
        entries.append(
            f"    '{spec.name}' = @{{ flags = {_ps_list(spec.flags)}; subs = @{{ {sub_entries} }} }}"
        )
    values: dict[str, list[str]] = {}
    for spec in [root, *root.subs, *(s for c in root.subs for s in c.subs)]:
        values.update(spec.values)
    value_entries = "\n".join(f"    '{f}' = {_ps_list(c)}" for f, c in sorted(values.items()))
    return "\n".join([
        "# unichef PowerShell completion. Generated by `unichef completion powershell`.",
        "Register-ArgumentCompleter -Native -CommandName unichef -ScriptBlock {",
        "  param($wordToComplete, $commandAst, $cursorPosition)",
        "  $commands = @{",
        *entries,
        "  }",
        "  $values = @{",
        value_entries,
        "  }",
        "  $words = @($commandAst.CommandElements | Select-Object -Skip 1 | ForEach-Object { $_.ToString() })",
        "  if ($wordToComplete -and $words.Count -gt 0) { $words = @($words | Select-Object -First ($words.Count - 1)) }",
        "  $positional = @(); $skip = $false; $prev = ''",
        "  foreach ($w in $words) {",
        "    $prev = $w",
        "    if ($skip) { $skip = $false; continue }",
        "    if ($values.ContainsKey($w)) { $skip = $true; continue }",
        "    if (-not $w.StartsWith('-')) { $positional += $w }",
        "  }",
        "  if ($values.ContainsKey($prev) -and $skip) { $candidates = $values[$prev] }",
        f"  elseif ($positional.Count -eq 0) {{ $candidates = @($commands.Keys) + {_ps_list(root.flags)} }}",
        "  else {",
        "    $entry = $commands[$positional[0]]",
        "    if ($null -eq $entry) { return }",
        "    if ($positional.Count -eq 1 -and $entry.subs.Count -gt 0) { $candidates = @($entry.subs.Keys) }",
        "    elseif ($positional[0] -eq 'op' -and $positional.Count -eq 1 -and -not $wordToComplete.StartsWith('-')) {",
        "      $candidates = @(unichef ops --ids 2>$null)",
        "    }",
        "    elseif ($positional.Count -ge 2 -and $entry.subs.ContainsKey($positional[1])) { $candidates = $entry.subs[$positional[1]] }",
        "    else { $candidates = $entry.flags }",
        "  }",
        "  $candidates | Where-Object { $_ -like \"$wordToComplete*\" } | Sort-Object -Unique | ForEach-Object {",
        "    [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)",
        "  }",
        "}",
        "",
    ])  # fmt: skip


GENERATORS = {"bash": bash, "zsh": zsh, "fish": fish, "powershell": powershell}


def script(shell: str) -> str:
    return GENERATORS[shell](model())


__all__ = ["UniChefParser", "script"]
