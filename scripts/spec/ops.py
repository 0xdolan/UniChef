"""Generate spec/ops.json, the operation metadata index, from the Python registry (PRD §2.1).

Runs inside the python-cli environment, which provides the ``unichef`` package. The
npm-core tests compare their registry with this file, so both cores share one op list.

    uv run --project packages/python-cli --locked python scripts/spec/ops.py
    uv run --project packages/python-cli --locked python scripts/spec/ops.py --check
"""

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

from unichef.core.registry import ArgSpec, Operation, all_operations

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "spec" / "ops.json"


def arg_entry(spec: ArgSpec) -> dict[str, Any]:
    """Only the fields that apply to the argument's kind."""
    out: dict[str, Any] = {"name": spec.name, "kind": spec.kind}
    if spec.kind != "steps":
        out["default"] = spec.default
    if spec.kind == "enum":
        out["options"] = list(spec.options)
    if spec.kind == "integer":
        if spec.minimum is not None:
            out["minimum"] = spec.minimum
        if spec.maximum is not None:
            out["maximum"] = spec.maximum
    if spec.kind == "bytes":
        out["encodings"] = list(spec.encodings)
        if spec.secret:
            out["secret"] = True
    if spec.kind == "regex":
        out["flags"] = spec.flags
    if spec.kind == "string" and spec.multiline:
        out["multiline"] = True
    return out


def reflow(text: str) -> str:
    """Join docstring line wraps; keep blank-line paragraph breaks."""
    return "\n\n".join(" ".join(p.split()) for p in re.split(r"\n\s*\n", text.strip()))


def op_entry(op: Operation) -> dict[str, Any]:
    return {
        "id": op.id,
        "name": op.name,
        "category": op.category,
        "description": reflow(op.description),
        "input": op.input_type,
        "output": op.output_type,
        "parity": op.parity,
        "args": [arg_entry(a) for a in op.args],
        "examples": [
            {"input": e.input, "args": dict(e.args), "output": e.output} for e in op.examples
        ],
    }


def build() -> str:
    doc = {
        "$comment": "Generated by scripts/spec/ops.py from the Python registry. Do not edit.",
        "ops": [op_entry(op) for op in all_operations()],
    }
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if spec/ops.json drifts")
    args = ap.parse_args()
    text = build()
    count = len(json.loads(text)["ops"])
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("ops-drift: spec/ops.json is stale; run make ops", file=sys.stderr)
            return 1
        print(f"ops-drift: ok ({count} ops)")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"spec/ops.json: {count} ops")
    return 0


if __name__ == "__main__":
    sys.exit(main())
